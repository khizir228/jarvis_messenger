class DBConn:
    def __init__(self):
        if USE_POSTGRES:
            if psycopg is None:
                raise RuntimeError("DATABASE_URL задан, но пакет psycopg не установлен")
            self.conn = psycopg.connect(DATABASE_URL, row_factory=dict_row, connect_timeout=10)
        else:
            self.conn = sqlite3.connect(DB_PATH, timeout=10)
            self.conn.row_factory = sqlite3.Row
            self.conn.execute("PRAGMA foreign_keys=ON")
            self.conn.execute("PRAGMA journal_mode=WAL")

    def execute(self, sql, params=()):
        if USE_POSTGRES:
            sql = sql.replace("?", "%s")
        return self.conn.execute(sql, params)

    def commit(self):
        self.conn.commit()

    def rollback(self):
        self.conn.rollback()

    def close(self):
        self.conn.close()

    def executescript(self, script):
        if USE_POSTGRES:
            for statement in [x.strip() for x in script.split(";") if x.strip()]:
                self.conn.execute(statement)
        else:
            self.conn.executescript(script)

def db():
    return DBConn()

def password_hash(password: str) -> str:
    import hashlib
    salt = secrets.token_bytes(16)
    digest = hashlib.pbkdf2_hmac("sha256", password.encode("utf-8"), salt, 260_000)
    return "pbkdf2$260000$" + salt.hex() + "$" + digest.hex()

def password_verify(password: str, stored: str) -> bool:
    import hashlib, hmac
    try:
        scheme, rounds, salt_hex, digest_hex = stored.split("$")
        if scheme != "pbkdf2":
            return False
        digest = hashlib.pbkdf2_hmac("sha256", password.encode("utf-8"), bytes.fromhex(salt_hex), int(rounds))
        return hmac.compare_digest(digest.hex(), digest_hex)
    except Exception:
        return False


def init_db():
    conn = db()
    if USE_POSTGRES:
        conn.executescript("""
        CREATE TABLE IF NOT EXISTS users (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            username TEXT UNIQUE NOT NULL,
            password_hash TEXT NOT NULL,
            display_name TEXT NOT NULL,
            avatar TEXT DEFAULT '',
            bio TEXT DEFAULT '',
            accent TEXT DEFAULT '#7c5cff',
            status TEXT DEFAULT 'online',
            created_at TEXT NOT NULL
        );
        CREATE TABLE IF NOT EXISTS rooms (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name TEXT NOT NULL,
            owner_id INTEGER NOT NULL REFERENCES users(id),
            invite_code TEXT UNIQUE,
            created_at TEXT NOT NULL
        );
        CREATE TABLE IF NOT EXISTS room_members (
            room_id INTEGER NOT NULL REFERENCES rooms(id) ON DELETE CASCADE,
            user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
            PRIMARY KEY(room_id,user_id)
        );
        CREATE TABLE IF NOT EXISTS messages (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            room_id INTEGER NOT NULL REFERENCES rooms(id) ON DELETE CASCADE,
            user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
            content TEXT NOT NULL,
            created_at TEXT NOT NULL,
            edited_at TEXT,
            reply_to INTEGER REFERENCES messages(id) ON DELETE SET NULL
        );
        CREATE TABLE IF NOT EXISTS reactions (
            message_id INTEGER NOT NULL REFERENCES messages(id) ON DELETE CASCADE,
            user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
            emoji TEXT NOT NULL,
            PRIMARY KEY(message_id,user_id,emoji)
        );
        CREATE INDEX IF NOT EXISTS idx_messages_room_id ON messages(room_id,id);
        CREATE INDEX IF NOT EXISTS idx_room_members_user ON room_members(user_id,room_id);
        """)
        conn.commit()
        conn.close()
        return

    conn.executescript("""
    CREATE TABLE IF NOT EXISTS users (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        username TEXT UNIQUE NOT NULL,
        password_hash TEXT NOT NULL,
        display_name TEXT NOT NULL,
        avatar TEXT DEFAULT '',
        bio TEXT DEFAULT '',
        accent TEXT DEFAULT '#7c5cff',
        status TEXT DEFAULT 'online',
        created_at TEXT NOT NULL
    );
    CREATE TABLE IF NOT EXISTS rooms (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        name TEXT NOT NULL,
        owner_id INTEGER NOT NULL,
        invite_code TEXT UNIQUE,
        created_at TEXT NOT NULL,
        FOREIGN KEY(owner_id) REFERENCES users(id)
    );
    CREATE TABLE IF NOT EXISTS room_members (
        room_id INTEGER NOT NULL,
        user_id INTEGER NOT NULL,
        PRIMARY KEY(room_id,user_id),
        FOREIGN KEY(room_id) REFERENCES rooms(id) ON DELETE CASCADE,
        FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
    );
    CREATE TABLE IF NOT EXISTS messages (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        room_id INTEGER NOT NULL,
        user_id INTEGER NOT NULL,
        content TEXT NOT NULL,
        created_at TEXT NOT NULL,
        edited_at TEXT,
        reply_to INTEGER,
        FOREIGN KEY(room_id) REFERENCES rooms(id) ON DELETE CASCADE,
        FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,
        FOREIGN KEY(reply_to) REFERENCES messages(id) ON DELETE SET NULL
    );
    CREATE TABLE IF NOT EXISTS reactions (
        message_id INTEGER NOT NULL,
        user_id INTEGER NOT NULL,
        emoji TEXT NOT NULL,
        PRIMARY KEY(message_id,user_id,emoji),
        FOREIGN KEY(message_id) REFERENCES messages(id) ON DELETE CASCADE,
        FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
    );
    CREATE INDEX IF NOT EXISTS idx_messages_room_id ON messages(room_id,id);
    CREATE INDEX IF NOT EXISTS idx_room_members_user ON room_members(user_id,room_id);
    """)
    cols = {r[1] for r in conn.execute("PRAGMA table_info(users)").fetchall()}
    if "status" not in cols:
        conn.execute("ALTER TABLE users ADD COLUMN status TEXT DEFAULT 'online'")
    room_cols = {r[1] for r in conn.execute("PRAGMA table_info(rooms)").fetchall()}
    if "invite_code" not in room_cols:
        conn.execute("ALTER TABLE rooms ADD COLUMN invite_code TEXT")
    msg_cols = {r[1] for r in conn.execute("PRAGMA table_info(messages)").fetchall()}
    if "edited_at" not in msg_cols:
        conn.execute("ALTER TABLE messages ADD COLUMN edited_at TEXT")
    if "reply_to" not in msg_cols:
        conn.execute("ALTER TABLE messages ADD COLUMN reply_to INTEGER")
    rows = conn.execute("SELECT id FROM rooms WHERE invite_code IS NULL OR invite_code='' ").fetchall()
    for r in rows:
        code = secrets.token_urlsafe(7).replace("-", "A").replace("_", "B")[:10].upper()
        while conn.execute("SELECT 1 FROM rooms WHERE invite_code=?", (code,)).fetchone():
            code = secrets.token_hex(5).upper()
        conn.execute("UPDATE rooms SET invite_code=? WHERE id=?", (code, r[0]))
    conn.commit()
    conn.close()


