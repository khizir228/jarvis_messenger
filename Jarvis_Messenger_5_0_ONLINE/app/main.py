@app.post("/api/register")
def register(data: AuthIn):
    username = clean_username(data.username)
    if len(data.password) < 6:
        raise HTTPException(400, "Пароль должен быть не короче 6 символов")
    display = (data.display_name or username).strip()[:40] or username
    conn = db()
    try:
        if USE_POSTGRES:
            cur = conn.execute("INSERT INTO users(username,password_hash,display_name,created_at) VALUES(?,?,?,?) RETURNING id", (username, password_hash(data.password), display, now_iso()))
            uid = cur.fetchone()["id"]
        else:
            cur = conn.execute("INSERT INTO users(username,password_hash,display_name,created_at) VALUES(?,?,?,?)", (username, password_hash(data.password), display, now_iso()))
            uid = cur.lastrowid
        code = secrets.token_hex(5).upper()
        if USE_POSTGRES:
            cur = conn.execute("INSERT INTO rooms(name,owner_id,invite_code,created_at) VALUES(?,?,?,?) RETURNING id", (f"{display}'s room", uid, code, now_iso()))
            rid = cur.fetchone()["id"]
        else:
            cur = conn.execute("INSERT INTO rooms(name,owner_id,invite_code,created_at) VALUES(?,?,?,?)", (f"{display}'s room", uid, code, now_iso()))
            rid = cur.lastrowid
        conn.execute("INSERT INTO room_members(room_id,user_id) VALUES(?,?)", (rid, uid))
        conn.commit()
        return {"token": make_token(uid), "user_id": uid, "room_id": rid}
    except Exception as exc:
        conn.rollback()
        if isinstance(exc, sqlite3.IntegrityError) or getattr(exc, "sqlstate", None) == "23505":
            raise HTTPException(409, "Такой логин уже занят")
        raise
    finally:
        conn.close()


@app.post("/api/login")
def login(data: AuthIn):
    conn = db(); row = conn.execute("SELECT * FROM users WHERE username=?", (data.username.strip(),)).fetchone(); conn.close()
