def now_iso():
    return datetime.now(timezone.utc).isoformat()


def make_token(user_id: int):
    return jwt.encode({"sub": str(user_id), "exp": datetime.now(timezone.utc) + timedelta(days=14)}, SECRET, algorithm="HS256")


def user_from_token(token: str):
    try:
        payload = jwt.decode(token, SECRET, algorithms=["HS256"])
        return int(payload["sub"])
    except Exception:
        raise HTTPException(401, "Сессия недействительна. Войдите снова.")


def clean_username(v: str):
    v = v.strip()
    if not re.fullmatch(r"[A-Za-zА-Яа-яЁё0-9_.-]{3,24}", v):
        raise HTTPException(400, "Логин: 3–24 символа, буквы, цифры, _, ., -")
    return v


def user_json(row):
    return {k: row[k] for k in ("id", "username", "display_name", "avatar", "bio", "accent", "status")}


def message_json(conn, message_id, viewer_id=None):
    row = conn.execute("""
        SELECT m.id,m.room_id,m.content,m.created_at,m.edited_at,m.reply_to,
               u.id user_id,u.username,u.display_name,u.avatar,u.status
        FROM messages m JOIN users u ON u.id=m.user_id WHERE m.id=?
    """, (message_id,)).fetchone()
    if not row:
        return None
    d = dict(row)
    d["reactions"] = [dict(x) for x in conn.execute("""
        SELECT emoji, COUNT(*) count,
        MAX(CASE WHEN user_id=? THEN 1 ELSE 0 END) mine
        FROM reactions WHERE message_id=? GROUP BY emoji ORDER BY emoji
    """, ((viewer_id if viewer_id is not None else d["user_id"]), message_id)).fetchall()]
    return d


